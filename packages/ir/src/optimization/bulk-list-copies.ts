import {
  instructionResult,
  type Block,
  type FunctionIR,
  type Instruction,
  type ModuleIR,
  type ScalarType,
  type Terminator,
} from "../scalar/index.ts";

export interface BulkListCopies {
  readonly module: ModuleIR;
  readonly visited: number;
  /** Copy loops given a bulk fast path. */
  readonly rewritten: number;
}

/** Fresh destinations larger than this keep the element-wise loop (its
 * write helper bounds the first vector the same way). */
const maxBulkElements = 65536;

interface ListHelper {
  readonly kind: "has" | "read" | "write";
  readonly header: number;
}

/** The direct-reference list helpers generated by lowerReferenceLists, by
 * name and IR shape: the read and presence accessors guard the header's root
 * field (field 1; field 0 is the logical length), and the writer allocates
 * no value cells (a stored undefined is the vector itself). Indexed by
 * function ID. */
function listHelpers(module: ModuleIR): (ListHelper | undefined)[] {
  const helpers: (ListHelper | undefined)[] = [];
  for (const fn of module.functions) {
    if (fn === undefined) throw "bulk copy function invariant";
    const name = fn.name;
    const kind: "has" | "read" | "write" | undefined = name.startsWith(
      "__tint_reference_list_has$",
    )
      ? "has"
      : name.startsWith("__tint_reference_list_read$")
        ? "read"
        : name.startsWith("__tint_reference_list_write$")
          ? "write"
          : undefined;
    if (kind === undefined) continue;
    let header = -1,
      cells = false,
      selfTest = false;
    for (const block of fn.blocks) {
      if (block === undefined) throw "bulk copy block invariant";
      for (const op of block.instructions) {
        if (op === undefined) throw "bulk copy instruction invariant";
        if (op.kind === "record-new") cells = true;
        if (op.kind === "binary" && op.operator === "===") selfTest = true;
      }
      const t = block.terminator;
      if (t.kind === "record" && header < 0) header = t.record;
    }
    if (header < 0 || cells || (kind === "read" && !selfTest)) continue;
    while (helpers.length < fn.id) helpers.push(undefined);
    const helper: ListHelper = { kind: kind, header: header };
    helpers[fn.id] = helper;
  }
  return helpers;
}

interface CopyLoop {
  readonly preheader: number;
  readonly header: number;
  readonly source: number;
  readonly target: number;
  readonly index: number;
  readonly count: number;
  /** The list header layout. */
  readonly layout: number;
}

function definitionIn(block: Block, id: number): Instruction | undefined {
  for (const op of block.instructions)
    if (op !== undefined && instructionResult(op) === id) return op;
  return undefined;
}
function loadSlot(block: Block, id: number): number {
  const op = definitionIn(block, id);
  return op !== undefined && op.kind === "load" ? op.slot : -1;
}

/** Slots whose every store in `fn` is the constant 1. */
function constantOneSlots(fn: FunctionIR): Uint8Array {
  const ones = new Uint8Array(fn.slots.length),
    others = new Uint8Array(fn.slots.length);
  for (const block of fn.blocks) {
    if (block === undefined) throw "bulk copy block invariant";
    for (const op of block.instructions) {
      if (op === undefined || op.kind !== "store") continue;
      const value = definitionIn(block, op.value);
      if (value !== undefined && value.kind === "constant" && value.value === 1)
        ones[op.slot] = 1;
      else others[op.slot] = 1;
    }
    const t = block.terminator;
    if (
      (t.kind === "record" || t.kind === "record-cell" || t.kind === "cell") &&
      t.operation === "read"
    )
      others[t.slot] = 1;
  }
  for (const slot of fn.parameters) if (slot !== undefined) others[slot] = 1;
  for (let slot = 0; slot < ones.length; slot++)
    if (others[slot] === 1) ones[slot] = 0;
  return ones;
}

/** `header: i < count ? has : exit`, `has: has(src, i) ? copy : step`,
 * `copy: write(dst, i, read(src, i)); step`, `step: i = i + 1; header`,
 * with the header entered from one jumping preheader. */
function recognize(
  fn: FunctionIR,
  header: Block,
  helpers: readonly (ListHelper | undefined)[],
  predecessors: readonly (readonly number[])[],
  ones: Uint8Array,
): CopyLoop | undefined {
  const term = header.terminator;
  if (term.kind !== "branch" || header.exception !== undefined)
    return undefined;
  const test = definitionIn(header, term.condition);
  if (test === undefined || test.kind !== "binary" || test.operator !== "<")
    return undefined;
  const index = loadSlot(header, test.left),
    count = loadSlot(header, test.right);
  if (index < 0 || count < 0 || header.instructions.length !== 3)
    return undefined;
  const presence = fn.blocks[term.consequent];
  if (presence === undefined || presence.exception !== undefined)
    return undefined;
  const presenceTerm = presence.terminator;
  if (presenceTerm.kind !== "branch" || presence.instructions.length !== 3)
    return undefined;
  const hasCall = definitionIn(presence, presenceTerm.condition);
  if (
    hasCall === undefined ||
    hasCall.kind !== "call" ||
    hasCall.environment !== undefined ||
    hasCall.arguments.length !== 2
  )
    return undefined;
  const list = helpers[hasCall.target];
  if (list === undefined || list.kind !== "has") return undefined;
  const source = loadSlot(presence, hasCall.arguments[0] ?? -1);
  if (source < 0 || loadSlot(presence, hasCall.arguments[1] ?? -1) !== index)
    return undefined;
  const copy = fn.blocks[presenceTerm.consequent],
    step = fn.blocks[presenceTerm.alternate];
  if (copy === undefined || step === undefined) return undefined;
  if (copy.exception !== undefined || step.exception !== undefined)
    return undefined;
  const copyTerm = copy.terminator;
  if (copyTerm.kind !== "jump" || copyTerm.target !== step.id) return undefined;
  // The copy block: loads, then read(src, i), then write(dst, i, value).
  let readOp: Instruction | undefined, writeOp: Instruction | undefined;
  for (const op of copy.instructions) {
    if (op === undefined) return undefined;
    if (op.kind === "load") continue;
    if (op.kind !== "call") return undefined;
    if (readOp === undefined) readOp = op;
    else if (writeOp === undefined) writeOp = op;
    else return undefined;
  }
  const reader = readOp,
    writer = writeOp;
  if (
    reader === undefined ||
    writer === undefined ||
    reader.kind !== "call" ||
    writer.kind !== "call" ||
    helpers[reader.target]?.kind !== "read" ||
    helpers[reader.target]?.header !== list.header ||
    helpers[writer.target]?.kind !== "write" ||
    helpers[writer.target]?.header !== list.header ||
    reader.environment !== undefined ||
    writer.environment !== undefined ||
    reader.id === undefined ||
    writer.arguments.length !== 3
  )
    return undefined;
  if (
    loadSlot(copy, reader.arguments[0] ?? -1) !== source ||
    loadSlot(copy, reader.arguments[1] ?? -1) !== index ||
    loadSlot(copy, writer.arguments[1] ?? -1) !== index ||
    writer.arguments[2] !== reader.id
  )
    return undefined;
  const target = loadSlot(copy, writer.arguments[0] ?? -1);
  if (target < 0 || target === index || target === count) return undefined;
  // step: i = i + 1, jump header.
  const stepTerm = step.terminator;
  if (
    stepTerm.kind !== "jump" ||
    stepTerm.target !== header.id ||
    step.instructions.length !== 4
  )
    return undefined;
  const store = step.instructions[3];
  if (store === undefined || store.kind !== "store" || store.slot !== index)
    return undefined;
  const sum = definitionIn(step, store.value);
  if (sum === undefined || sum.kind !== "binary" || sum.operator !== "+")
    return undefined;
  const left = definitionIn(step, sum.left),
    right = definitionIn(step, sum.right);
  const isOne = (op: Instruction | undefined): boolean =>
    op !== undefined &&
    ((op.kind === "constant" && op.value === 1) ||
      (op.kind === "load" && ones[op.slot] === 1));
  if (!(
    (left !== undefined &&
      left.kind === "load" &&
      left.slot === index &&
      isOne(right)) ||
    (right !== undefined &&
      right.kind === "load" &&
      right.slot === index &&
      isOne(left))
  ))
    return undefined;
  // Entered from one preheader ending in a jump; nothing else enters the
  // loop's inner blocks.
  const outside = (predecessors[header.id] ?? []).filter(
    (id) => id !== step.id,
  );
  const preheader = outside[0];
  if (outside.length !== 1 || preheader === undefined) return undefined;
  const pre = fn.blocks[preheader];
  if (pre === undefined || pre.terminator.kind !== "jump") return undefined;
  for (const inner of [presence, copy, step]) {
    if (inner === undefined) return undefined;
    if ((predecessors[inner.id] ?? []).length !== (inner === step ? 2 : 1))
      return undefined;
  }
  // The source, destination and count are loop invariant.
  for (const block of [header, presence, copy, step]) {
    if (block === undefined) return undefined;
    for (const op of block.instructions)
      if (
        op !== undefined &&
        op.kind === "store" &&
        (op.slot === source || op.slot === target || op.slot === count)
      )
        return undefined;
  }
  return {
    preheader,
    header: header.id,
    source,
    target,
    index,
    count,
    layout: list.header,
  };
}

/** Bulk fast paths for the element copy loops `slice` lowers to (see
 * recognize): when the destination list has no vector yet (a fresh result,
 * all holes) and the source is dense, the loop's effect is to allocate the
 * destination's vector and copy the source's elements: holes stay holes
 * (`has` skips them) and a stored undefined (the source vector itself) is
 * rebased to the destination. The counter must start at 0, the count be an
 * integer in (0, min(destination length, 65536)], so no write extends the
 * destination's logical length; the counter ends at the count, as after the
 * loop. Any other state runs the original loop. */
export function bulkListCopies(
  module: ModuleIR,
  budget: number,
): BulkListCopies | undefined {
  if (!Number.isSafeInteger(budget) || budget < 0) return undefined;
  let visited = module.functions.length;
  if (visited > budget) return undefined;
  const helpers = listHelpers(module);
  if (helpers.length === 0) return { module, visited, rewritten: 0 };
  let rewritten = 0;
  const functions: FunctionIR[] = [];
  for (const fn of module.functions) {
    if (fn === undefined) throw "bulk copy function invariant";
    let calls = false;
    for (const block of fn.blocks) {
      if (block === undefined) throw "bulk copy block invariant";
      if (++visited > budget) return undefined;
      for (const op of block.instructions)
        if (op !== undefined && op.kind === "call") {
          const target = op.target;
          if (helpers[target]?.kind === "has") calls = true;
        }
    }
    if (!calls) {
      functions.push(fn);
      continue;
    }
    const result = rewriteFunction(fn, helpers);
    rewritten += result.rewritten;
    visited += result.visited;
    if (visited > budget) return undefined;
    functions.push(result.fn);
  }
  return {
    module: rewritten === 0 ? module : { ...module, functions },
    visited,
    rewritten,
  };
}

function rewriteFunction(
  fn: FunctionIR,
  helpers: readonly (ListHelper | undefined)[],
): { fn: FunctionIR; rewritten: number; visited: number } {
  const count = fn.blocks.length;
  for (let index = 0; index < count; index++)
    if (fn.blocks[index]?.id !== index) return { fn, rewritten: 0, visited: 0 };
  let visited = 0,
    nextValue = 0;
  const predecessors: number[][] = [];
  for (let index = 0; index < count; index++) predecessors.push([]);
  for (const block of fn.blocks) {
    if (block === undefined) throw "bulk copy block invariant";
    for (const op of block.instructions) {
      if (op === undefined) throw "bulk copy instruction invariant";
      visited++;
      const id = instructionResult(op);
      if (id !== undefined && id >= nextValue) nextValue = id + 1;
    }
    for (const target of successors(block.terminator)) {
      if (target === undefined) throw "bulk copy successor invariant";
      predecessors[target]?.push(block.id);
    }
    const handler = block.exception?.target;
    if (handler !== undefined) predecessors[handler]?.push(block.id);
  }
  const ones = constantOneSlots(fn);
  const loops: CopyLoop[] = [];
  for (const block of fn.blocks) {
    if (block === undefined) throw "bulk copy block invariant";
    const loop = recognize(fn, block, helpers, predecessors, ones);
    if (loop !== undefined) loops.push(loop);
  }
  if (loops.length === 0) return { fn, rewritten: 0, visited };
  const blocks: Block[] = fn.blocks.slice();
  const slots: ScalarType[] = fn.slots.slice();
  for (const loop of loops) {
    if (loop === undefined) throw "bulk copy loop invariant";
    const v = (): number => nextValue++;
    const sourceRoot = slots.length;
    slots.push("optional-reference");
    const targetRoot = slots.length;
    slots.push("optional-reference");
    const targetLength = slots.length;
    slots.push("number");
    const copied = slots.length;
    slots.push("number");
    const fallback = loop.header,
      header = loop.layout;
    const ids = {
      sourceRoot: blocks.length,
      sourceDense: blocks.length + 1,
      targetRoot: blocks.length + 2,
      targetLength: blocks.length + 3,
      empty: blocks.length + 4,
      start: blocks.length + 5,
      bounded: blocks.length + 6,
      capped: blocks.length + 7,
      positive: blocks.length + 8,
      integral: blocks.length + 9,
      copy: blocks.length + 10,
      publish: blocks.length + 11,
    };
    const preheader = blocks[loop.preheader];
    if (preheader === undefined) throw "bulk copy preheader invariant";
    const jump = preheader.terminator;
    if (jump.kind !== "jump") throw "bulk copy preheader invariant";
    blocks[loop.preheader] = {
      ...preheader,
      terminator: { ...jump, target: ids.sourceRoot },
    };
    const branch = (
      condition: number,
      yes: number,
      no: number,
    ): Terminator => ({
      kind: "branch",
      condition,
      consequent: yes,
      alternate: no,
      start: 0,
      end: 0,
    });
    // Source root (a layout mismatch takes the loop).
    const s0 = v();
    blocks.push({
      id: ids.sourceRoot,
      instructions: [
        { kind: "load", id: s0, slot: loop.source, start: 0, end: 0 },
      ],
      terminator: {
        kind: "record",
        object: s0,
        record: header,
        field: 1,
        operation: "read",
        slot: sourceRoot,
        consequent: ids.sourceDense,
        alternate: fallback,
        start: 0,
        end: 0,
      },
    });
    const r0 = v(),
      dense = v();
    blocks.push({
      id: ids.sourceDense,
      instructions: [
        { kind: "load", id: r0, slot: sourceRoot, start: 0, end: 0 },
        {
          kind: "reference-vector-is",
          id: dense,
          vector: r0,
          start: 0,
          end: 0,
        },
      ],
      terminator: branch(dense, ids.targetRoot, fallback),
    });
    const d0 = v();
    blocks.push({
      id: ids.targetRoot,
      instructions: [
        { kind: "load", id: d0, slot: loop.target, start: 0, end: 0 },
      ],
      terminator: {
        kind: "record",
        object: d0,
        record: header,
        field: 1,
        operation: "read",
        slot: targetRoot,
        consequent: ids.targetLength,
        alternate: fallback,
        start: 0,
        end: 0,
      },
    });
    const d1 = v();
    blocks.push({
      id: ids.targetLength,
      instructions: [
        { kind: "load", id: d1, slot: loop.target, start: 0, end: 0 },
      ],
      terminator: {
        kind: "record",
        object: d1,
        record: header,
        field: 0,
        operation: "read",
        slot: targetLength,
        consequent: ids.empty,
        alternate: fallback,
        start: 0,
        end: 0,
      },
    });
    // The destination has no root yet (a fresh, all-hole list).
    const t0 = v(),
      present = v();
    blocks.push({
      id: ids.empty,
      instructions: [
        { kind: "load", id: t0, slot: targetRoot, start: 0, end: 0 },
        {
          kind: "unary",
          id: present,
          operator: "truthy",
          operand: t0,
          start: 0,
          end: 0,
        },
      ],
      terminator: branch(present, fallback, ids.start),
    });
    const i0 = v(),
      zero = v(),
      atStart = v();
    blocks.push({
      id: ids.start,
      instructions: [
        { kind: "load", id: i0, slot: loop.index, start: 0, end: 0 },
        { kind: "constant", id: zero, value: 0, start: 0, end: 0 },
        {
          kind: "binary",
          id: atStart,
          operator: "===",
          left: i0,
          right: zero,
          start: 0,
          end: 0,
        },
      ],
      terminator: branch(atStart, ids.bounded, fallback),
    });
    // 0 < count <= min(destination length, maxBulkElements).
    const c0 = v(),
      length = v(),
      within = v();
    blocks.push({
      id: ids.bounded,
      instructions: [
        { kind: "load", id: c0, slot: loop.count, start: 0, end: 0 },
        { kind: "load", id: length, slot: targetLength, start: 0, end: 0 },
        {
          kind: "binary",
          id: within,
          operator: "<=",
          left: c0,
          right: length,
          start: 0,
          end: 0,
        },
      ],
      terminator: branch(within, ids.capped, fallback),
    });
    const c5 = v(),
      limit = v(),
      below = v();
    blocks.push({
      id: ids.capped,
      instructions: [
        { kind: "load", id: c5, slot: loop.count, start: 0, end: 0 },
        {
          kind: "constant",
          id: limit,
          value: maxBulkElements,
          start: 0,
          end: 0,
        },
        {
          kind: "binary",
          id: below,
          operator: "<=",
          left: c5,
          right: limit,
          start: 0,
          end: 0,
        },
      ],
      terminator: branch(below, ids.positive, fallback),
    });
    const c6 = v(),
      zero1 = v(),
      positive = v();
    blocks.push({
      id: ids.positive,
      instructions: [
        { kind: "load", id: c6, slot: loop.count, start: 0, end: 0 },
        { kind: "constant", id: zero1, value: 0, start: 0, end: 0 },
        {
          kind: "binary",
          id: positive,
          operator: ">",
          left: c6,
          right: zero1,
          start: 0,
          end: 0,
        },
      ],
      terminator: branch(positive, ids.integral, fallback),
    });
    const c1 = v(),
      integer = v();
    blocks.push({
      id: ids.integral,
      instructions: [
        { kind: "load", id: c1, slot: loop.count, start: 0, end: 0 },
        {
          kind: "unary",
          id: integer,
          operator: "is-integer",
          operand: c1,
          start: 0,
          end: 0,
        },
      ],
      terminator: branch(integer, ids.copy, fallback),
    });
    // Allocate and publish the destination vector, copy, finish the loop.
    const c2 = v(),
      fresh = v(),
      wrapped = v(),
      d2 = v(),
      r1 = v(),
      sourceVector = v(),
      sourceLength = v(),
      c3 = v(),
      n = v(),
      d3 = v(),
      targetVector = v(),
      n1 = v(),
      c4 = v();
    const publish = ids.publish;
    blocks.push({
      id: ids.copy,
      instructions: [
        { kind: "load", id: c2, slot: loop.count, start: 0, end: 0 },
        {
          kind: "reference-vector-new",
          id: fresh,
          length: c2,
          start: 0,
          end: 0,
        },
        { kind: "reference-wrap", id: wrapped, value: fresh, start: 0, end: 0 },
        { kind: "store", slot: targetRoot, value: wrapped, start: 0, end: 0 },
        { kind: "load", id: d2, slot: loop.target, start: 0, end: 0 },
      ],
      terminator: {
        kind: "record",
        object: d2,
        record: header,
        field: 1,
        operation: "write",
        slot: targetRoot,
        consequent: publish,
        alternate: fallback,
        start: 0,
        end: 0,
      },
    });
    blocks.push({
      id: publish,
      instructions: [
        { kind: "load", id: r1, slot: sourceRoot, start: 0, end: 0 },
        {
          kind: "reference-value",
          id: sourceVector,
          value: r1,
          start: 0,
          end: 0,
        },
        {
          kind: "reference-vector-length",
          id: sourceLength,
          vector: sourceVector,
          start: 0,
          end: 0,
        },
        { kind: "load", id: c3, slot: loop.count, start: 0, end: 0 },
        {
          kind: "binary",
          id: n,
          operator: "min",
          left: c3,
          right: sourceLength,
          start: 0,
          end: 0,
        },
        { kind: "store", slot: copied, value: n, start: 0, end: 0 },
        { kind: "load", id: d3, slot: targetRoot, start: 0, end: 0 },
        {
          kind: "reference-value",
          id: targetVector,
          value: d3,
          start: 0,
          end: 0,
        },
        { kind: "load", id: n1, slot: copied, start: 0, end: 0 },
        {
          kind: "reference-vector-copy",
          source: sourceVector,
          target: targetVector,
          count: n1,
          rebase: true,
          start: 0,
          end: 0,
        },
        { kind: "load", id: c4, slot: loop.count, start: 0, end: 0 },
        { kind: "store", slot: loop.index, value: c4, start: 0, end: 0 },
      ],
      terminator: { kind: "jump", target: fallback, start: 0, end: 0 },
    });
  }
  for (let index = 0; index < blocks.length; index++)
    if (blocks[index]?.id !== index) throw "bulk copy block order invariant";
  return { fn: { ...fn, slots, blocks }, rewritten: loops.length, visited };
}

function successors(term: Terminator): number[] {
  if (term.kind === "jump") return [term.target];
  if (
    term.kind === "branch" ||
    term.kind === "record" ||
    term.kind === "record-cell" ||
    term.kind === "cell"
  )
    return term.consequent === term.alternate
      ? [term.consequent]
      : [term.consequent, term.alternate];
  return [];
}
