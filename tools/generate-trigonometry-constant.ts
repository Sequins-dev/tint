import { writeFileSync } from "node:fs";
// Machin's identity: pi = 16 atan(1/5) - 4 atan(1/239). Fixed-point
// integer arithmetic uses 1792 guard bits beyond the emitted precision.
const workingBits = 4096n;
const outputBits = 2304n;
const scale = 1n << workingBits;
function arctangentInverse(divisor: bigint): bigint {
  const square = divisor * divisor;
  let power = divisor,
    sum = 0n,
    denominator = 1n,
    positive = true;
  while (true) {
    const term = scale / power / denominator;
    if (term === 0n) return sum;
    sum += positive ? term : -term;
    positive = !positive;
    power *= square;
    denominator += 2n;
  }
}
const pi = 16n * arctangentInverse(5n) - 4n * arctangentInverse(239n);
const scaled = (2n * scale * (1n << outputBits)) / pi;
const hex = scaled.toString(16);
const base = 1n << 26n;
const limbs: number[] = [];
for (let remaining = scaled; remaining > 0n; remaining >>= 26n)
  limbs.push(Number(remaining & (base - 1n)));
writeFileSync(
  "packages/foundation/src/numeric/binary64-trigonometry/constant.ts",
  `// Generated by tools/generate-trigonometry-constant.ts using Machin's identity.\n// floor((2/pi) * 2^2304); no host floating-point approximation of pi is used.\nexport const twoOverPiBits = 2304;\nexport const twoOverPiHex = ${JSON.stringify(hex)};\n// Little-endian base-2^26 digits matching @tint/foundation/numeric/big-integer.\nexport function twoOverPiDigits(): readonly number[] {\n  return ${JSON.stringify(limbs)};\n}\n`,
);
