import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const url =
  "https://www.unicode.org/Public/17.0.0/ucd/PropertyValueAliases.txt";
const digest =
  "64e9a5f76f7a1e8b5a47d6a1f9a26522a251208f5276bdfa1559dac7cf2e827a";
const input = process.argv[2];
const bytes =
  input === undefined
    ? new Uint8Array(await (await fetch(url)).arrayBuffer())
    : readFileSync(input);
if (createHash("sha256").update(bytes).digest("hex") !== digest)
  throw new Error("Unicode 17.0.0 source checksum mismatch");
const text = new TextDecoder().decode(bytes);
function aliases(property: string): string[] {
  const result = new Map<string, string>();
  for (const line of text.split("\n")) {
    const fields = line
      .split("#")[0]!
      .split(";")
      .map((field) => field.trim());
    if (fields[0] !== property) continue;
    const canonical = fields[2]!;
    for (const alias of fields.slice(1))
      if (alias) result.set(alias, canonical);
  }
  if (result.size === 0) throw new Error("Missing aliases: " + property);
  return [...result]
    .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
    .flat();
}
writeFileSync(
  "packages/foundation/src/regexp/syntax/unicode-property-data.ts",
  `// Generated by tools/generate-regexp-unicode-aliases.ts. Unicode 17.0.0.\n// Source: ${url}\n// SHA-256: ${digest}\n// Unicode data copyright and permission notice: ../../../docs/regexp/syntax/LICENSE-UNICODE.txt\nexport const categoryAliases: readonly string[] = ${JSON.stringify(aliases("gc"))};\nexport const scriptAliases: readonly string[] = ${JSON.stringify(aliases("sc"))};\n`,
);
