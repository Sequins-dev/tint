import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const url =
  "https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/bcp47/timezone.xml";
const expected =
  "54ce7d9f1d385101e24356df7d48ae62cf2acc4421378da60a4007d2488c1aad";
const local = process.argv[2];
const response = local === undefined ? await fetch(url) : undefined;
if (response !== undefined && !response.ok)
  throw new Error("CLDR timezone data: HTTP " + response.status);
const bytes =
  local === undefined
    ? new Uint8Array(await response!.arrayBuffer())
    : readFileSync(local);
if (createHash("sha256").update(bytes).digest("hex") !== expected)
  throw new Error("CLDR 48 timezone checksum mismatch");
const text = new TextDecoder().decode(bytes),
  mappings = new Map<string, string>();
// This is extraction from one checksum-pinned data file, not a general XML parser.
for (const match of text.matchAll(/<type\b([^>]+)\/>/g)) {
  const attributes = new Map(
    [...match[1]!.matchAll(/([a-zA-Z]+)="([^"]*)"/g)].map((row) => [
      row[1]!,
      row[2]!,
    ]),
  );
  const aliases = attributes.get("alias")?.split(" ");
  if (aliases === undefined) continue;
  let primary = attributes.get("iana") ?? aliases[0]!;
  if (primary === "Etc/UTC" || primary === "Etc/GMT" || primary === "GMT")
    primary = "UTC";
  for (const alias of aliases) {
    if (
      !/^[A-Za-z0-9_+./-]+$/.test(alias) ||
      !/^[A-Za-z0-9_+./-]+$/.test(primary)
    )
      throw new Error("Unexpected CLDR identifier encoding");
    const previous = mappings.get(alias);
    if (previous !== undefined && previous !== primary)
      throw new Error("Conflicting CLDR alias: " + alias);
    mappings.set(alias, primary);
  }
}
if (mappings.size !== 601 || mappings.get("UTC") !== "UTC")
  throw new Error("Unexpected CLDR 48 mapping population");
const rows = [...mappings]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([alias, primary]) => JSON.stringify(alias + "|" + primary));
writeFileSync(
  "packages/js-runtime/src/objects/time-zone-primary-data.ts",
  `// Generated by tools/generate-time-zone-primary-identifiers.ts.\n// CLDR 48: ${url}\n// SHA-256 ${expected}\n// Unicode License V3: ../../LICENSE-UNICODE.txt\nexport const timeZonePrimaryDataVersion = "CLDR 48";\nexport const timeZonePrimaryMappings: readonly string[] = [\n${rows.map((row) => "  " + row + ",").join("\n")}\n];\n`,
);
console.log(
  "Generated " +
    mappings.size +
    " primary-zone mappings from checksum-pinned CLDR 48 data.",
);
