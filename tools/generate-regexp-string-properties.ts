import { canonicalize } from "../packages/foundation/src/regexp/engine/case-fold.ts";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const sources = [
  [
    "emoji-sequences.txt",
    "12cc8267dc33cbd11ed32bcf6fc5dc2ad9c7a77bae1bdfba2f41b1b9b3ead8dd",
  ],
  [
    "emoji-zwj-sequences.txt",
    "5b25441daed2322b068c5e70cda522946a4f0274df864445a1965a92e5fc5cad",
  ],
] as const;
const properties = new Map<string, string[]>();
for (const [name, hash] of sources) {
  console.error("Unicode 17: " + name);
  const local = process.argv[2];
  const response =
    local === undefined
      ? await fetch("https://www.unicode.org/Public/17.0.0/emoji/" + name)
      : undefined;
  if (response !== undefined && !response.ok)
    throw Error(name + ": HTTP " + response.status);
  const bytes =
    local === undefined
      ? new Uint8Array(await response!.arrayBuffer())
      : readFileSync(join(local, name));
  if (createHash("sha256").update(bytes).digest("hex") !== hash)
    throw Error(name + ": Unicode 17 checksum mismatch");
  for (const line of new TextDecoder().decode(bytes).split("\n")) {
    const [points, property] = line
      .split("#")[0]!
      .split(";")
      .map((x) => x.trim());
    if (!points || !property) continue;
    const values = properties.get(property) ?? [];
    if (points.includes("..")) {
      const [low, high] = points.split("..").map((x) => parseInt(x, 16));
      for (let value = low!; value <= high!; value++)
        values.push(String.fromCodePoint(value));
    } else
      values.push(
        String.fromCodePoint(
          ...points.split(/\s+/).map((x) => parseInt(x, 16)),
        ),
      );
    properties.set(property, values);
  }
}
let output =
  "// Generated by tools/generate-regexp-string-properties.ts. Unicode 17.0.0.\n// Unicode license: ../../../docs/regexp/engine/LICENSE-UNICODE.txt\n";
for (const [name, hash] of sources)
  output += "// " + name + " sha256 " + hash + "\n";
properties.set("RGI_Emoji", [...properties.values()].flat());
const names = [...properties.keys()].sort();
output +=
  "export const stringPropertyNames: readonly string[] = " +
  JSON.stringify(names) +
  ";\n";
output +=
  "export const stringPropertyValues: readonly (readonly string[])[] = [\n";
for (const name of names)
  output +=
    JSON.stringify([...new Set(properties.get(name)!)].sort().join("\0")) +
    '.split("\\0"),\n';
output += "];\n";
function fold(text: string): string {
  return Array.from(text, (character) =>
    String.fromCodePoint(canonicalize(character.codePointAt(0)!, true)),
  ).join("");
}
output +=
  "export const foldedStringPropertyValues: readonly (readonly string[])[] = [\n";
for (const name of names)
  output +=
    JSON.stringify(
      [...new Set(properties.get(name)!.map(fold))].sort().join("\0"),
    ) + '.split("\\0"),\n';
output += "];\n";
output +=
  "export const stringPropertyMaxLengths: readonly number[] = " +
  JSON.stringify(
    names.map((name) =>
      Math.max(
        ...properties
          .get(name)!
          .flatMap((text) => [text.length, fold(text).length]),
      ),
    ),
  ) +
  ";\n";
writeFileSync(
  "packages/foundation/src/regexp/engine/string-property-data.ts",
  output,
);
