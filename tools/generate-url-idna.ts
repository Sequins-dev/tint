import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const version = "17.0.0";
const files = [
  [
    "idna/IdnaMappingTable.txt",
    "87f05505dc026fdb2bff16132bdc68a8014675836882a9a2b1844540ad3be382",
  ],
  [
    "ucd/extracted/DerivedBidiClass.txt",
    "4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4",
  ],
  [
    "ucd/extracted/DerivedJoiningType.txt",
    "f39ebe974825d6736aee15582250307aa532b2cfab3caf3f86bd23fddc9c5c4d",
  ],
] as const;
const local = process.argv[2];
const inputs = await Promise.all(
  files.map(async ([file, digest]) => {
    const name = file.slice(file.lastIndexOf("/") + 1);
    const bytes = await (async () => {
      if (local !== undefined) return readFileSync(join(local, name));
      const response = await fetch(
        "https://www.unicode.org/Public/" + version + "/" + file,
      );
      if (!response.ok) throw Error(file + " returned HTTP " + response.status);
      return new Uint8Array(await response.arrayBuffer());
    })();
    assert.equal(
      createHash("sha256").update(bytes).digest("hex"),
      digest,
      file,
    );
    return new TextDecoder().decode(bytes);
  }),
);

function fields(text: string): string[][] {
  return text
    .split("\n")
    .map((line) =>
      (line.split("#")[0] ?? "").split(";").map((field) => field.trim()),
    )
    .filter((row) => row.length > 1);
}
function range(field: string): [number, number] {
  const [first, last = first] = field.split("..");
  assert.ok(first && last);
  return [parseInt(first, 16), parseInt(last, 16)];
}
function encodedPoint(point: number): string {
  return String.fromCharCode(point & 65535, point >>> 16);
}
function table(name: string, value: string): string {
  // Escape UTF-16 code units explicitly, including unpaired surrogates in
  // packed integer words. Limit literal length for the native source loader.
  const parts: string[] = [];
  for (let i = 0; i < value.length; i += 192) {
    let word = '"';
    for (let j = i; j < Math.min(i + 192, value.length); j++)
      word += "\\u" + value.charCodeAt(j).toString(16).padStart(4, "0");
    parts.push(word + '"');
  }
  return "export const " + name + " =\n  " + parts.join(" +\n  ") + ";\n";
}

let mappingEnds = "",
  mappingInfo = "",
  mappingText = "";
let previous = -1;
for (const row of fields(inputs[0] ?? "")) {
  const [start, last] = range(row[0] ?? "");
  assert.equal(start, previous + 1);
  previous = last;
  const status = row[1];
  const tag =
    status === "valid" || status === "deviation"
      ? 1
      : status === "mapped"
        ? 2
        : status === "ignored"
          ? 3
          : 0;
  const mapped =
    tag === 2
      ? String.fromCodePoint(
          ...(row[2] ?? "").split(" ").map((point) => parseInt(point, 16)),
        )
      : "";
  assert.ok(mappingText.length <= 65535 && mapped.length < 64);
  mappingEnds += encodedPoint(last);
  mappingInfo += String.fromCharCode(
    (mapped.length << 2) | tag,
    mappingText.length,
  );
  mappingText += mapped;
}
assert.equal(previous, 0x10ffff);

const bidi = new Uint8Array(0x110000);
const joining = new Uint8Array(bidi.length);
const bidiClasses = [
  "L",
  "R",
  "AL",
  "EN",
  "AN",
  "ES",
  "CS",
  "ET",
  "ON",
  "BN",
  "NSM",
];
const joinClasses = ["U", "L", "R", "D", "T"];
for (const row of fields(inputs[1] ?? "")) {
  const [first, last] = range(row[0] ?? "");
  const kind = bidiClasses.indexOf(row[1] ?? "");
  bidi.fill(kind < 0 ? 11 : kind, first, last + 1);
}
for (const row of fields(inputs[2] ?? "")) {
  const [first, last] = range(row[0] ?? "");
  const kind = joinClasses.indexOf(row[1] ?? "");
  joining.fill(kind < 0 ? 0 : kind, first, last + 1);
}
let contextEnds = "",
  contextInfo = "";
for (let point = 0; point < bidi.length; point++) {
  const value = (bidi[point] ?? 0) | ((joining[point] ?? 0) << 4);
  const next = point + 1;
  if (
    next < bidi.length &&
    value === ((bidi[next] ?? 0) | ((joining[next] ?? 0) << 4))
  )
    continue;
  contextEnds += encodedPoint(point);
  contextInfo += String.fromCharCode(value);
}

writeFileSync(
  "packages/js-runtime/src/objects/url-idna-data.ts",
  "// Generated by tools/generate-url-idna.ts from Unicode 17.0.0 data.\n" +
    "// Copyright and permission: ../../LICENSE-UNICODE.txt\n" +
    table("mappingEnds", mappingEnds) +
    table("mappingInfo", mappingInfo) +
    table("mappingText", mappingText) +
    table("contextEnds", contextEnds) +
    table("contextInfo", contextInfo),
);
