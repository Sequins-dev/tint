import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const url =
  "https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt";
const digest =
  "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08";
const input = process.argv[2];
const bytes =
  input === undefined
    ? new Uint8Array(await (await fetch(url)).arrayBuffer())
    : readFileSync(input);
if (createHash("sha256").update(bytes).digest("hex") !== digest)
  throw new Error("Unicode 17.0.0 source checksum mismatch");
const text = new TextDecoder().decode(bytes);
function ranges(property: string): number[] {
  const entries: [number, number][] = [];
  for (const line of text.split("\n")) {
    const match = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)\s*#/.exec(line);
    if (match?.[3] === property)
      entries.push([
        parseInt(match[1]!, 16),
        parseInt(match[2] ?? match[1]!, 16),
      ]);
  }
  entries.sort((a, b) => a[0] - b[0]);
  const merged: number[] = [];
  for (const [start, end] of entries) {
    if (merged.length > 0 && start <= merged[merged.length - 1]! + 1)
      merged[merged.length - 1] = Math.max(end, merged[merged.length - 1]!);
    else merged.push(start, end);
  }
  if (merged.length === 0)
    throw new Error("Missing Unicode property: " + property);
  return merged;
}
writeFileSync(
  "packages/foundation/src/unicode/identifiers/ranges.ts",
  `// Generated by tools/generate-unicode-identifiers.ts. Unicode 17.0.0.\n// Source: ${url}\n// SHA-256: ${digest}\n// Unicode data copyright and permission notice: ../LICENSE-UNICODE.txt\nexport const startRanges: readonly number[] = ${JSON.stringify(ranges("ID_Start"))};\nexport const continueRanges: readonly number[] = ${JSON.stringify(ranges("ID_Continue"))};\n`,
);
