import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const inputs = [
  [
    "UnicodeData",
    "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
  ],
  [
    "DerivedNormalizationProps",
    "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
  ],
] as const;
const texts: string[] = [];
for (const [name, hash] of inputs) {
  const local = process.argv[2];
  const response =
    local === undefined
      ? await fetch(`https://www.unicode.org/Public/17.0.0/ucd/${name}.txt`)
      : undefined;
  if (response !== undefined && !response.ok)
    throw Error(`${name}: HTTP ${response.status}`);
  const bytes =
    local === undefined
      ? new Uint8Array(await response!.arrayBuffer())
      : readFileSync(join(local, `${name}.txt`));
  assert.equal(
    createHash("sha256").update(bytes).digest("hex"),
    hash,
    name + " checksum",
  );
  texts.push(new TextDecoder().decode(bytes));
}
const excluded = new Set<number>();
for (const line of texts[1]!.split("\n")) {
  const fields = line
    .split("#")[0]!
    .split(";")
    .map((field) => field.trim());
  if (fields[1] !== "Full_Composition_Exclusion") continue;
  const [start, end] = fields[0]!.split("..");
  for (
    let point = parseInt(start!, 16);
    point <= parseInt(end ?? start!, 16);
    point++
  )
    excluded.add(point);
}
const points: number[] = [],
  info: number[] = [],
  values: number[] = [],
  combiningPoints: number[] = [],
  classes: number[] = [],
  pairs: [number, number][] = [];
for (const line of texts[0]!.split("\n")) {
  if (!line) continue;
  const fields = line.split(";"),
    point = parseInt(fields[0]!, 16),
    order = Number(fields[3]);
  if (order !== 0) {
    combiningPoints.push(point);
    classes.push(order);
  }
  if (!fields[5]) continue;
  const parts = fields[5].split(" "),
    compatibility = parts[0]!.startsWith("<");
  if (compatibility) parts.shift();
  const mapping = parts.map((part) => parseInt(part, 16));
  points.push(point);
  info.push(values.length * 2 + (compatibility ? 1 : 0));
  values.push(...mapping);
  if (!compatibility && mapping.length === 2 && !excluded.has(point))
    pairs.push([mapping[0]! * 0x110000 + mapping[1]!, point]);
}
info.push(values.length * 2);
pairs.sort((a, b) => a[0] - b[0]);
for (let index = 1; index < pairs.length; index++)
  assert.ok(pairs[index]![0] > pairs[index - 1]![0]);
function packed(numbers: readonly number[], units: number): string {
  let text = "";
  for (const value of numbers) {
    assert.ok(
      Number.isSafeInteger(value) && value >= 0 && value < 65536 ** units,
    );
    for (let unit = 0; unit < units; unit++)
      text +=
        "\\u" +
        (Math.floor(value / 65536 ** unit) % 65536)
          .toString(16)
          .padStart(4, "0");
  }
  return '"' + text + '"';
}
const tables: readonly [string, readonly number[], number][] = [
  ["decompositionPoints", points, 2],
  ["decompositionInfo", info, 2],
  ["decompositionValues", values, 2],
  ["combiningPoints", combiningPoints, 2],
  ["combiningClasses", classes, 1],
  ["compositionKeys", pairs.map((pair) => pair[0]), 3],
  ["compositionValues", pairs.map((pair) => pair[1]), 2],
];
const header =
  "// Generated by tools/generate-unicode-normalization.ts. Unicode 17.0.0.\n// Source: https://www.unicode.org/Public/17.0.0/ucd/\n// Copyright and permission: ../../../docs/unicode/LICENSE-UNICODE.txt\n// Little-endian packed UTF-16 units; codepoints/offsets use2, keys3, classes1.\n";
writeFileSync(
  "packages/foundation/src/unicode/normalization/data.ts",
  header +
    inputs.map(([name, hash]) => `// ${name}.txt SHA-256: ${hash}\n`).join("") +
    tables
      .map(
        ([name, values, units]) =>
          `export const ${name}: string = ${packed(values, units)};\n`,
      )
      .join(""),
);
console.log(
  JSON.stringify({
    unicodeVersion: "17.0.0",
    decompositions: points.length,
    values: values.length,
    classes: classes.length,
    compositions: pairs.length,
  }),
);
