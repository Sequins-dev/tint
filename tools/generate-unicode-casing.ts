import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const inputs = [
  [
    "UnicodeData",
    "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
  ],
  [
    "SpecialCasing",
    "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588",
  ],
] as const;
const texts: string[] = [];
for (const [name, hash] of inputs) {
  const local = process.argv[2];
  const response =
    local === undefined
      ? await fetch(`https://www.unicode.org/Public/17.0.0/ucd/${name}.txt`)
      : undefined;
  if (response !== undefined && !response.ok)
    throw new Error(`${name}: HTTP ${response.status}`);
  const bytes =
    local === undefined
      ? new Uint8Array(await response!.arrayBuffer())
      : readFileSync(join(local, `${name}.txt`));
  if (createHash("sha256").update(bytes).digest("hex") !== hash)
    throw new Error(`${name}: Unicode 17.0.0 checksum mismatch`);
  texts.push(new TextDecoder().decode(bytes));
}
function fields(text: string): string[][] {
  return text
    .split("\n")
    .map((line) =>
      line
        .split("#")[0]!
        .split(";")
        .map((field) => field.trim()),
    )
    .filter((row) => row.length > 1);
}
const lower = new Map<number, string>(),
  upper = new Map<number, string>();
for (const row of fields(texts[0]!)) {
  if (row[12])
    upper.set(
      parseInt(row[0]!, 16),
      String.fromCodePoint(parseInt(row[12], 16)),
    );
  if (row[13])
    lower.set(
      parseInt(row[0]!, 16),
      String.fromCodePoint(parseInt(row[13], 16)),
    );
}
for (const row of fields(texts[1]!)) {
  if (row[4]) {
    if (row[4] !== "Final_Sigma" && !/^(tr|az|lt)( |$)/.test(row[4]))
      throw new Error("Unknown casing context: " + row[4]);
    continue;
  }
  const code = parseInt(row[0]!, 16);
  const decode = (text: string) =>
    String.fromCodePoint(
      ...text
        .split(" ")
        .filter(Boolean)
        .map((x) => parseInt(x, 16)),
    );
  lower.set(code, decode(row[1]!));
  upper.set(code, decode(row[3]!));
}
function table(name: string, map: Map<number, string>): string {
  const pairs = [...map]
    .filter(([point, text]) => text !== String.fromCodePoint(point))
    .sort((a, b) => a[0] - b[0]);
  return `export const ${name}Points: readonly number[] = ${JSON.stringify(pairs.map((x) => x[0]))};\nexport const ${name}Mappings: readonly string[] = ${JSON.stringify(pairs.map((x) => x[1]))};\n`;
}
writeFileSync(
  "packages/foundation/src/unicode/casing/data.ts",
  `// Generated by tools/generate-unicode-casing.ts. Unicode 17.0.0.\n// Source: https://www.unicode.org/Public/17.0.0/ucd/\n${inputs.map(([name, hash]) => `// ${name}.txt SHA-256: ${hash}\n`).join("")}// Copyright and permission: ../LICENSE-UNICODE.txt\n${table("lower", lower)}${table("upper", upper)}`,
);
